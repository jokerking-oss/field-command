export function expansionTiles(mapId) {
  const map = byId.get(mapId);
  if (!map) return null;
  const owners = new Map();
  map.ownerIndices.forEach((indices, seat) => indices.forEach((index) => owners.set(index, seat)));
  const tiles = [];
  for (let y = 0; y < map.height; y++) {
    for (let x = 0; x < map.width; x++) {
      const index = y * map.width + x;
      tiles.push({ x, y, type: TILE_CODES[map.rows[y][x]], owner: owners.get(index) ?? null, capture: 20, captureBy: null });
    }
  }
  return tiles;
}
export function expansionSpawns(mapId) {
  const map = byId.get(mapId);
  return map ? map.starts.map(([x, y], seat) => ({ seat, x, y })) : null;
}
